import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { env } from './config/env.js';
import { errorHandler } from './middleware/errors.js';
import { authRouter } from './modules/auth/auth.routes.js';
import { employeesRouter } from './modules/employees/employees.routes.js';
import { teamsRouter } from './modules/teams/teams.routes.js';
import { defectsRouter } from './modules/defects/defects.routes.js';
import { schedulesRouter } from './modules/schedules/schedules.routes.js';
import { attendanceRouter } from './modules/attendance/attendance.routes.js';
import { requestsRouter } from './modules/requests/requests.routes.js';
import { dashboardRouter } from './modules/dashboard/dashboard.routes.js';
import { notificationsRouter } from './modules/notifications/notifications.routes.js';
import { auditRouter } from './modules/audit/audit.routes.js';
import { reportsRouter } from './modules/reports/reports.routes.js';

export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.CLIENT_ORIGIN, credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.get('/api/health', (_req, res) => res.json({ status: 'ok', service: 'hydrowork-api' }));
app.use('/api/auth/login', rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: 'draft-7', legacyHeaders: false }));
app.use('/api/auth', authRouter);
app.use('/api/employees', employeesRouter);
app.use('/api/teams', teamsRouter);
app.use('/api/defects', defectsRouter);
app.use('/api/schedules', schedulesRouter);
app.use('/api/attendance', attendanceRouter);
app.use('/api/requests', requestsRouter);
app.use('/api/dashboard', dashboardRouter);
app.use('/api/notifications', notificationsRouter);
app.use('/api/audit', auditRouter);
app.use('/api/reports', reportsRouter);
app.use((_req, res) => res.status(404).json({ message: 'Không tìm thấy địa chỉ API.' }));
app.use(errorHandler);
